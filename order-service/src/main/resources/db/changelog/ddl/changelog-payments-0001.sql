CREATE TABLE IF NOT EXISTS payments
(
    payment_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       INTEGER,
    user_id        BIGINT,
    is_payed       BOOLEAN,
    payment_status VARCHAR(255),
    created_at     TIMESTAMP(6) WITH TIME ZONE,
    updated_at     TIMESTAMP(6) WITH TIME ZONE
);
